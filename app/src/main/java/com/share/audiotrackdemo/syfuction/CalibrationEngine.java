    /**
     * 核心算法：线性插值计算
     * @param type 声音类型 (如 13 代表语言噪音)
     * @param targetDb 目标分贝 (如 65dB)
     * @return 最终作用于 PCM 数据的增益倍数
     */
    public static double calculateGain(int type, int targetDb) {
        // 1. 限制边界，防止爆音或非法输入
        int db = Math.max(0, Math.min(120, targetDb));

        for (double[][] typeData : GAIN_TABLES) {
            // 匹配类型 ID
            if ((int) typeData[0][0] == type) {
                // 2. 在该类型的数组中寻找所在的 dB 区间
                for (int i = 1; i < typeData.length - 1; i++) {
                    int dbLow = (int) typeData[i][0];
                    double gainLow = typeData[i][1];
                    int dbHigh = (int) typeData[i + 1][0];
                    double gainHigh = typeData[i + 1][1];

                    if (db >= dbLow && db <= dbHigh) {
                        // 3. 执行线性插值公式：y = y1 + (x - x1) * (y2 - y1) / (x2 - x1)
                        double fraction = (double)(db - dbLow) / (dbHigh - dbLow);
                        double finalGain = gainLow + fraction * (gainHigh - gainLow);

                        Log.d(TAG, "Type:" + type + " dB:" + db + " -> Computed Gain:" + finalGain);
                        return finalGain;
                    }
                }
            }
        }

        // 4. 如果没找到匹配类型，返回 1.0 (不增不减) 作为安全保底
        Log.w(TAG, "未找到类型 " + type + " 的校准数据，使用默认增益 1.0");
        return 1.0;
    }

    /**
     * 将 16-bit PCM 字节流应用增益并防止溢出
     */
    public static byte[] applyGainTo16BitPcm(byte[] rawData, double gain) {
        if (rawData == null) return null;
        byte[] out = new byte[rawData.length];

        for (int i = 0; i < rawData.length; i += 2) {
            // 1. 合并两个字节为一个 16 位短整型 (小端序)
            short sample = (short) ((rawData[i + 1] << 8) | (rawData[i] & 0xFF));

            // 2. 应用增益并进行数值截断（Clipping）防止爆音
            int adjustedSample = (int) (sample * gain);
            if (adjustedSample > Short.MAX_VALUE) adjustedSample = Short.MAX_VALUE;
            else if (adjustedSample < Short.MIN_VALUE) adjustedSample = Short.MIN_VALUE;

            // 3. 拆回两个字节
            out[i] = (byte) (adjustedSample & 0xFF);
            out[i + 1] = (byte) ((adjustedSample >> 8) & 0xFF);
        }
        return out;
    }
