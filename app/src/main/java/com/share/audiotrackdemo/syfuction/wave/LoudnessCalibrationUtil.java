    public static double getTypeNomuberDbEx(double[][][] array, double freq, double vol) {
        int frequencyIndex = -1;
/*
        // pgh 20250421 added: 当频率<125时，采用默认最小值125；当频率>8000时，采用默认频率8000 // FRQ_MIN
        if(freq<FRQ_MIN)
            freq = FRQ_MIN;
        if(freq>FRQ_MAX)
            freq = FRQ_MAX;
*/
        for (int i = 0; i < array.length; i++) {
            if (array[i][0][0] == freq) {
                frequencyIndex = i;
                break;
            }
        }

        // 当指定频率存在于表格中时，使用单线性插值
        if (frequencyIndex != -1) {
            double minDb = array[frequencyIndex][1][0];
            double maxDb = array[frequencyIndex][array[frequencyIndex].length - 1][0];
            if (vol < minDb || vol > maxDb) {
                return 1.0 * vol;
            }

            for (int i = 1; i < array[frequencyIndex].length - 1; i++) {
                if (vol == array[frequencyIndex][i][0]) {
                    return array[frequencyIndex][i][1] * vol;
                } else if (vol > array[frequencyIndex][i][0] && vol < array[frequencyIndex][i + 1][0]) {
                    double lowerDb = array[frequencyIndex][i][0];
                    double upperDb = array[frequencyIndex][i + 1][0];
                    double lowerGain = array[frequencyIndex][i][1];
                    double upperGain = array[frequencyIndex][i + 1][1];
                    double gain = linearInterpolation(lowerDb, upperDb, lowerGain, upperGain, vol);
                    return gain * vol;
                }
            }
            return array[frequencyIndex][array[frequencyIndex].length - 1][1] * vol;
        }

        // 当指定频率不存在于表格中时，使用双线性插值
        int lowerFreqIndex = -1;
        int upperFreqIndex = -1;
        for (int i = 0; i < array.length; i++) {
            if (array[i][0][0] < freq) {
                lowerFreqIndex = i;
            } else if (array[i][0][0] > freq) {
                upperFreqIndex = i;
                break;
            }
        }

        if (lowerFreqIndex == -1 || upperFreqIndex == -1) {
            return 1.0 * vol;
        }

        double lowerFreq = array[lowerFreqIndex][0][0];
        double upperFreq = array[upperFreqIndex][0][0];

        // 计算相邻频率对应分贝的输出
        double lowerOutput = getTypeNomuberDbEx(array, lowerFreq, vol);
        double upperOutput = getTypeNomuberDbEx(array, upperFreq, vol);

        // 在频率维度进行插值
        double gain = linearInterpolation(lowerFreq, upperFreq, lowerOutput / vol, upperOutput / vol, freq);
        return gain * vol;
    }


