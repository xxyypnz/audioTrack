    public static double getTypeNomuberDb(double[][][] array,double freq,double vol){
        for (int i = 0; i < array.length; i++) {
            for (int i1 = 1; i1 < array[i].length; i1++) {
                if (array[i][0][0]==freq&&array[i][i1][0]==vol) {
                    return array[i][i1][1]*vol;
                }
            }
        }
//        没找到 统一返回数值
        return 1.0*vol;
    }

    // 单线性插值方法
    private static double linearInterpolation(double lowerDb, double upperDb, double lowerGain, double upperGain, double vol) {
        return lowerGain + ((vol - lowerDb) * (upperGain - lowerGain) / (upperDb - lowerDb));
    }

